#!/bin/sh
# Files as an OCaml list of (name, contents): the test pages built into
# ariadne (about:test/NAME) and their expected dumps, built into the
# tests. Usage: gen-strings.sh VALUE FILE... > module.ml
# A file's name is its base name without its extension.
set -eu
value=$1; shift
delim=ariadne_file
echo "(* generated by gen-strings.sh: do not edit *)"
echo "let $value = ["
for f in "$@"; do
    if grep -q "|$delim}" "$f"; then
        echo "gen-strings.sh: $f contains |$delim}" >&2; exit 1
    fi
    name=$(basename "$f"); name=${name%.*}
    printf '  ("%s", {%s|' "$name" "$delim"
    cat "$f"
    printf '|%s});\n' "$delim"
done
echo "]"
