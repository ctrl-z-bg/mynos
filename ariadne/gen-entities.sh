#!/bin/sh
# The HTML Standard's named character references (third_party/whatwg-entities/
# entities.json, one per line) as an OCaml list: the name without its "&"
# (with its ";" when it has one), and its code points.
# Usage: gen-entities.sh entities.json > entities_data.ml
set -eu
echo "(* generated by gen-entities.sh from the HTML Standard's entities.json: do not edit *)"
echo "let all = ["
sed -n 's/^  "&\([A-Za-z0-9;]*\)": { "codepoints": \[\([0-9, ]*\)\].*/  ("\1", [|\2|]);/p' "$1" |
    sed 's/, \([0-9]\)/; \1/g'
echo "]"
